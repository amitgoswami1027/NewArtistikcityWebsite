#!/bin/bash
# =====================================================================
#  ArtistikCity - deploy one image on the EC2 server (run as root; GitHub Actions calls it through AWS SSM).
#
#    ec2-deploy.sh <image-uri>        deploy that image (e.g. 1234.dkr.ecr.ap-south-1.amazonaws.com/artistikcity:<git-sha>)
#    ec2-deploy.sh --rollback         go back to the image that ran before the current one
#    ec2-deploy.sh --status           show what is running
#
#  Steps: 1) settings file from Secrets Manager + SSM Parameter Store  2) pull the image  3) database migrations
#  (stops here on error, the running site is untouched)  4) replace the container  5) health check on /healthz
#  6) if the new version is not healthy within ~3 minutes: start the previous image again and exit 1.
#
#  Server settings come from /opt/artistikcity/deploy.conf (written when the server was created):
#    AWS_REGION, S3_BUCKET, DB_HOST, DB_NAME, DB_SECRET_ARN, SSM_PATH, LOG_GROUP, APP_URL
#    and optionally ORIGIN_SECRET_ARN, OTP_SECRET_ARN (secrets generated by infra/artistikcity.yml)
# =====================================================================
set -euo pipefail
umask 077

BASE="${ARTISTIK_BASE:-/opt/artistikcity}"
CONF="$BASE/deploy.conf"
STATE="$BASE/state"
NAME=artistikcity
HOST_PORT="${HOST_PORT:-80}"
HEALTH_URL="http://127.0.0.1:${HOST_PORT}/healthz"
HEALTH_TRIES="${HEALTH_TRIES:-60}"      # x 3 s
MYSQL_IMAGE="${MYSQL_IMAGE:-public.ecr.aws/docker/library/mysql:8.4}"   # Docker Hub mirror without pull limits

log() { echo "[$(date -u +%H:%M:%S)] $*"; }
die() { echo "ERROR: $*" >&2; exit 1; }

[ -f "$CONF" ] || die "$CONF is missing (it is written by the EC2 user data)"
# shellcheck disable=SC1090
source "$CONF"
: "${AWS_REGION:?}" "${S3_BUCKET:?}" "${DB_HOST:?}" "${DB_NAME:?}" "${DB_SECRET_ARN:?}" "${SSM_PATH:?}" "${LOG_GROUP:?}" "${APP_URL:?}"
mkdir -p "$STATE"
touch "$STATE/history"

current_image() { cat "$STATE/current" 2>/dev/null || true; }

# ---------------------------------------------------------------- settings
db_credentials() {   # prints "username<TAB>password" from the RDS-managed secret
  aws secretsmanager get-secret-value --region "$AWS_REGION" --secret-id "$DB_SECRET_ARN" --query SecretString --output text |
    python3 -c 'import json,sys; s=json.load(sys.stdin); print(s["username"] + "\t" + s["password"])'
}

secret_text() {      # plain-text secret value
  aws secretsmanager get-secret-value --region "$AWS_REGION" --secret-id "$1" --query SecretString --output text
}

write_env_file() {   # $1 = output file
  local out="$1" tmp creds user pass
  tmp="$(mktemp "$BASE/.env.XXXXXX")"
  creds="$(db_credentials)"
  user="${creds%%$'\t'*}"; pass="${creds#*$'\t'}"
  {
    echo "DB_URL=jdbc:mysql://${DB_HOST}:3306/${DB_NAME}?useUnicode=true&characterEncoding=UTF-8&sslMode=REQUIRED"
    echo "DB_USERNAME=${user}"
    echo "DB_PASSWORD=${pass}"
    echo "DB_INIT=never"
    echo "STORAGE_DRIVER=s3"
    echo "S3_BUCKET=${S3_BUCKET}"
    echo "AWS_REGION=${AWS_REGION}"
    echo "APP_URL=${APP_URL}"
    echo "TRUST_CLOUDFRONT=true"
    echo "SESSION_COOKIE_SECURE=true"
    echo "AUTH_COOKIE_SECURE=true"
    echo "PAYMENT_TEST_MODE=false"
    echo "TZ=${APP_TIMEZONE:-Asia/Kolkata}"
    # everything stored under $SSM_PATH (OTP_SECRET, ORIGIN_VERIFY_SECRET, RAZORPAY_KEY, MAIL_HOST, ...);
    # a value set there overrides the defaults above
    aws ssm get-parameters-by-path --region "$AWS_REGION" --path "$SSM_PATH" --recursive --with-decryption --output json |
      python3 -c '
import json, re, sys
for p in json.load(sys.stdin)["Parameters"]:
    name = p["Name"].rsplit("/", 1)[-1]
    value = p["Value"]
    if not re.fullmatch(r"[A-Z][A-Z0-9_]*", name):
        sys.exit("SSM parameter name must look like AN_ENV_VAR: " + p["Name"])
    if "\n" in value or "\r" in value:
        sys.exit("SSM parameter " + p["Name"] + " contains a line break")
    print(name + "=" + value)'
    # secrets generated by the CloudFormation stack come last, so they always win: the origin secret must be the
    # one CloudFront sends, otherwise every request would get 403
    if [ -n "${ORIGIN_SECRET_ARN:-}" ]; then echo "ORIGIN_VERIFY_SECRET=$(secret_text "$ORIGIN_SECRET_ARN")"; fi
    if [ -n "${OTP_SECRET_ARN:-}" ]; then echo "OTP_SECRET=$(secret_text "$OTP_SECRET_ARN")"; fi
  } > "$tmp"
  # last definition wins (docker reads them in order); keep the file tidy anyway
  tac "$tmp" | awk -F= '!seen[$1]++' | tac > "$tmp.new"
  rm -f "$tmp"
  # check before replacing, so a bad change in SSM never breaks the file a later rollback / restart uses
  if ! grep -q '^ORIGIN_VERIFY_SECRET=.\{16,\}' "$tmp.new"; then
    rm -f "$tmp.new"; die "SSM parameter ${SSM_PATH}/ORIGIN_VERIFY_SECRET is missing or shorter than 16 characters (see docs/AWS-DEPLOY.md)"
  fi
  if ! grep -q '^OTP_SECRET=.\{16,\}' "$tmp.new"; then
    rm -f "$tmp.new"; die "SSM parameter ${SSM_PATH}/OTP_SECRET is missing or shorter than 16 characters (see docs/AWS-DEPLOY.md)"
  fi
  chmod 600 "$tmp.new"
  mv -f "$tmp.new" "$out"
}

# ---------------------------------------------------------------- docker helpers
ecr_login() {   # $1 = image uri
  local registry="${1%%/*}"
  case "$registry" in
    *.dkr.ecr.*.amazonaws.com) aws ecr get-login-password --region "$AWS_REGION" | docker login --username AWS --password-stdin "$registry" >/dev/null ;;
  esac
}

start_container() {   # $1 = image
  local image="$1" tag="${1##*:}"
  docker rm -f "$NAME" >/dev/null 2>&1 || true
  docker run -d --name "$NAME" --restart unless-stopped \
    -p "${HOST_PORT}:8080" \
    --env-file "$BASE/app.env" \
    --memory "${APP_MEMORY:-1400m}" \
    --log-driver awslogs --log-opt awslogs-region="$AWS_REGION" --log-opt awslogs-group="$LOG_GROUP" \
    --log-opt awslogs-stream="app-${tag:0:12}-$(date -u +%Y%m%d%H%M%S)" \
    "$image" >/dev/null
}

healthy() {
  local i
  for i in $(seq 1 "$HEALTH_TRIES"); do
    if curl -fsS --max-time 5 "$HEALTH_URL" >/dev/null 2>&1; then return 0; fi
    if ! docker ps -q --filter "name=^${NAME}$" --filter status=running | grep -q .; then
      log "the container stopped"; return 1
    fi
    sleep 3
  done
  return 1
}

migrate() {   # $1 = image: copies database/ + deploy/ out of the image and runs db-migrate.sh in the mysql image
  local image="$1" work cid creds
  work="$(mktemp -d "$BASE/migrate.XXXXXX")"
  cid="$(docker create "$image")"
  docker cp "$cid:/app/database" "$work/database"
  docker cp "$cid:/app/deploy" "$work/deploy"
  docker rm "$cid" >/dev/null
  chmod -R a+rX "$work"
  creds="$(db_credentials)"
  docker pull -q "$MYSQL_IMAGE" >/dev/null
  if ! docker run --rm --network host -v "$work:/work:ro" \
      -e DB_HOST="$DB_HOST" -e DB_NAME="$DB_NAME" -e DB_USER="${creds%%$'\t'*}" -e MYSQL_PWD="${creds#*$'\t'}" \
      -e DB_DIR=/work/database -e LOAD_SEED="${LOAD_SEED:-false}" -e LOAD_DEMO="${LOAD_DEMO:-false}" \
      "$MYSQL_IMAGE" bash /work/deploy/db-migrate.sh; then
    rm -rf "$work"
    return 1
  fi
  rm -rf "$work"
}

prune_images() {   # keep the current and previous image of this repository, remove older ones
  local keep_a keep_b repo
  keep_a="$(current_image)"; keep_b="$(tail -n 1 "$STATE/history" 2>/dev/null || true)"
  repo="${keep_a%:*}"
  docker images --format '{{.Repository}}:{{.Tag}}' | grep "^${repo}:" | while read -r img; do
    if [ "$img" != "$keep_a" ] && [ "$img" != "$keep_b" ]; then docker rmi "$img" >/dev/null 2>&1 || true; fi
  done
  docker image prune -f >/dev/null 2>&1 || true
}

# ---------------------------------------------------------------- commands
deploy() {   # $1 = image, $2 = "migrate" or "skip-migrations"
  local image="$1" previous
  previous="$(current_image)"
  log "deploying $image (now running: ${previous:-nothing})"

  log "1/5 settings"
  write_env_file "$BASE/app.env"

  log "2/5 pulling the image"
  ecr_login "$image"
  docker pull -q "$image" >/dev/null

  if [ "$2" = "migrate" ]; then
    log "3/5 database migrations"
    migrate "$image" || die "database migration failed - nothing was changed on the running site"
  else
    log "3/5 database migrations skipped (rollback)"
  fi

  log "4/5 starting the new version"
  start_container "$image"

  log "5/5 health check ($HEALTH_URL)"
  if healthy; then
    if [ -n "$previous" ] && [ "$previous" != "$image" ]; then echo "$previous" >> "$STATE/history"; fi
    echo "$image" > "$STATE/current"
    prune_images
    log "OK - $image is live"
    return 0
  fi

  log "the new version did not become healthy; last log lines:"
  docker logs --tail 80 "$NAME" 2>&1 || true
  if [ -n "$previous" ]; then
    log "rolling back to $previous"
    start_container "$previous"
    if healthy; then log "rolled back - $previous is live again"; else log "WARNING: the previous version is not healthy either"; fi
  fi
  die "deploy of $image failed"
}

case "${1:-}" in
  --status)
    echo "current : $(current_image)"
    echo "previous: $(tail -n 1 "$STATE/history" 2>/dev/null || true)"
    docker ps --filter "name=^${NAME}$" --format 'container: {{.Image}}  {{.Status}}'
    curl -fsS --max-time 5 "$HEALTH_URL" && echo
    ;;
  --rollback)
    prev="$(tail -n 1 "$STATE/history" 2>/dev/null || true)"
    [ -n "$prev" ] || die "no previous image recorded"
    sed -i '$ d' "$STATE/history"
    deploy "$prev" skip-migrations      # the image we leave becomes "previous", so a second --rollback undoes this one
    ;;
  ""|-*)
    die "usage: $0 <image-uri> | --rollback | --status" ;;
  *)
    deploy "$1" "${MIGRATE:-migrate}" ;;
esac
